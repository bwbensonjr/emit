#!/usr/bin/env python3
"""Independent arbitrary-precision MRG32k3a oracle for Emit SRFI 27.

This uses Python matrix arithmetic rather than the Scheme implementation's
bounded arithmetic. Run with --check to validate committed fixtures.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys

M1 = 4294967087
M2 = 4294944443
INITIAL = [1062452522, 2961816100, 342112271, 2854655037, 3321940838, 3542344109]
A1 = [[0, 1403580, M1 - 810728], [1, 0, 0], [0, 1, 0]]
A2 = [[527612, 0, M2 - 1370589], [1, 0, 0], [0, 1, 0]]


def product(a, b, modulus):
    return [[sum(a[r][k] * b[k][c] for k in range(3)) % modulus
             for c in range(3)] for r in range(3)]


def power(a, n, modulus):
    result = [[int(r == c) for c in range(3)] for r in range(3)]
    while n:
        if n & 1:
            result = product(result, a, modulus)
        a = product(a, a, modulus)
        n >>= 1
    return result


def jump_state(i, j):
    exponent = 16 + (i % (1 << 28)) * (1 << 127) + (j % (1 << 28)) * (1 << 76)
    return [row[0] for a, modulus in [(A1, M1), (A2, M2)]
            for row in power(a, exponent, modulus)]


class RandomSource:
    def __init__(self, i=None, j=None):
        self.state = INITIAL.copy() if i is None else jump_state(i, j)

    def seed(self, i, j):
        self.state = jump_state(i, j)

    def snapshot(self):
        return self.state.copy()

    def core(self):
        a, b, c, d, e, f = self.state
        x = (1403580 * b - 810728 * c) % M1
        y = (527612 * d - 1370589 * f) % M2
        self.state = [x, a, b, y, d, e]
        return (x - y) % M1

    def bits(self, count):
        result = 0
        while count:
            width = min(30, count)
            bound = 1 << width
            quotient = M1 // bound
            limit = quotient * bound
            x = self.core()
            while x >= limit:
                x = self.core()
            result = result * bound + x // quotient
            count -= width
        return result

    def integer(self, n):
        if not isinstance(n, int) or n <= 0 or n >= (1 << 60):
            raise ValueError("bound outside Emit exact-integer range")
        if n == 1:
            self.core()
            return 0
        width = (n - 1).bit_length()
        x = self.bits(width)
        while x >= n:
            x = self.bits(width)
        return x

    def real(self):
        x = self.bits(53)
        while x == 0:
            x = self.bits(53)
        return x * (2.0 ** -53)


def fixture():
    cases = []
    for pair in [(0, 0), (1, 0), (0, 1), (17, 3), ((1 << 60) - 1, (1 << 60) - 1)]:
        source = RandomSource(*pair)
        initial = source.snapshot()
        cores = [source.core() for _ in range(8)]
        source.seed(*pair)
        bounds = [1, 3, 10, (1 << 32) + 1, (1 << 60) - 1, 2, 1000]
        draws = [source.integer(n) for n in bounds]
        reals = [source.real() for _ in range(3)]
        cases.append({"seed": pair, "state": initial, "core": cores,
                      "bounds": bounds, "integers": draws,
                      "reals": reals, "final_state": source.snapshot()})
    return {"upstream_revision": "a547c5508d648c61e73bebed2bcd2283fba5abaa",
            "algorithm": "mrg32k3a-v1", "cases": cases}


def scheme_fixture(data):
    def datum(x):
        if isinstance(x, (list, tuple)):
            return "(" + " ".join(datum(v) for v in x) + ")"
        return repr(x)
    rows = [[c["seed"], c["state"], c["bounds"], c["integers"], c["reals"], c["final_state"]]
            for c in data["cases"]]
    return "; Generated by reference.py; independent arbitrary-precision fixtures.\n(define known-answers '" + datum(rows) + ")\n"


def narrate(message):
    if os.environ.get("EMIT_VERBOSITY", "default") not in ("quiet", "q", "0"):
        print(message, file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    target = root / "known-answers.json"
    data = fixture()
    text = json.dumps(data, indent=2) + "\n"
    scheme = scheme_fixture(data)
    scheme_target = root / "known-answers.scm"
    if args.check:
        if target.read_text() != text or scheme_target.read_text() != scheme:
            raise SystemExit("SRFI 27 known-answer fixture differs; regenerate reference.py")
        narrate(f"verify {target} [5 streams, sha256 {hashlib.sha256(text.encode()).hexdigest()}]")
    else:
        target.write_text(text)
        scheme_target.write_text(scheme)
        narrate(f"generate arbitrary-precision reference -> {target} [{len(text)} bytes]")
    assert jump_state(0, 0) == INITIAL


if __name__ == "__main__":
    main()
